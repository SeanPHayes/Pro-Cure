/**
 * Regenerates infra/cdk/lib/subscriptions.ts from each service's declared `subscriptions`.
 *
 *   pnpm --filter @procure/infra-cdk gen:subscriptions        # or: npx tsx scripts/gen-subscriptions.ts
 *   … --check                                                  # exit 1 if the file is out of date (CI)
 *
 * Imports services/<name>/src/service.ts dynamically (tsx resolves the workspace TypeScript). A service
 * that is missing or fails to import keeps its previous entry from the existing subscriptions.ts, so
 * a half-written service never wipes its routing rules. Run it whenever a service adds or removes an
 * `on('event.type', …)` handler, and commit the result: the EventBridge rules are generated from it.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { SERVICE_NAMES, type ServiceName } from '../lib/services.js';
import { SUBSCRIPTIONS as PREVIOUS } from '../lib/subscriptions.js';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '../../..');
const outFile = join(here, '../lib/subscriptions.ts');
const check = process.argv.includes('--check');

// Importing service modules must not need real infrastructure.
process.env.APP_ENV ??= 'local';
process.env.LOG_LEVEL ??= 'fatal';

const result = {} as Record<ServiceName, string[]>;
const notes: string[] = [];

for (const name of SERVICE_NAMES) {
  const file = join(root, 'services', name, 'src/service.ts');
  if (!existsSync(file)) {
    result[name] = [...(PREVIOUS[name] ?? [])];
    notes.push(`${name}: service.ts missing — kept previous list`);
    continue;
  }
  try {
    const mod = (await import(pathToFileURL(file).href)) as Record<string, unknown>;
    const def = Object.values(mod).find(
      (v): v is { name: string; subscriptions?: { type: string }[] } =>
        typeof v === 'object' && v !== null && (v as { name?: unknown }).name === name,
    );
    if (!def) throw new Error('no exported ServiceDefinition with matching name');
    result[name] = [...new Set((def.subscriptions ?? []).map((s) => s.type))].sort();
  } catch (err) {
    result[name] = [...(PREVIOUS[name] ?? [])];
    notes.push(`${name}: import failed (${(err as Error).message.split('\n')[0]}) — kept previous list`);
  }
}

const body = SERVICE_NAMES.map(
  (n) => `  ${n}: [${result[n].length ? `\n${result[n].map((t) => `    '${t}',`).join('\n')}\n  ` : ''}],`,
).join('\n');

const content = `/**
 * Event types each service consumes. EventBridge rules route these detail-types to the service's SQS
 * queue (lib/stacks/events-stack.ts).
 *
 * GENERATED by scripts/gen-subscriptions.ts from each services/<name>/src/service.ts \`subscriptions\`.
 * Do not edit by hand — run \`pnpm --filter @procure/infra-cdk gen:subscriptions\`.
 */
import type { ServiceName } from './services.js';

export const SUBSCRIPTIONS: Record<ServiceName, readonly string[]> = {
${body}
};
`;

for (const n of notes) console.warn(`warn: ${n}`);
const current = existsSync(outFile) ? readFileSync(outFile, 'utf8') : '';
if (check) {
  if (current !== content) {
    console.error('lib/subscriptions.ts is out of date — run gen:subscriptions and commit the result.');
    process.exit(1);
  }
  console.log('lib/subscriptions.ts is up to date.');
} else {
  writeFileSync(outFile, content);
  console.log(`wrote ${outFile}`);
  for (const n of SERVICE_NAMES) console.log(`  ${n.padEnd(10)} ${result[n].join(', ') || '—'}`);
}
// Service modules may hold open handles (pools are lazy, but be safe).
process.exit(0);
